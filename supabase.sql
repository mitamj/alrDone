-- Ainayya Studio Log database setup / migration.
-- Safe to run on the existing starter database. Existing work_entries are preserved.

create table if not exists public.work_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  work_date date not null default current_date,
  title text not null,
  category text not null default 'Content Posting',
  collection text,
  product text,
  format text not null default 'Other',
  start_time time,
  end_time time,
  manual_hours numeric(7,2),
  status text not null default 'In progress',
  notes text,
  created_at timestamptz not null default now()
);

alter table public.work_entries add column if not exists activity_type text;
alter table public.work_entries add column if not exists collection_id bigint;
alter table public.work_entries add column if not exists product_id bigint;
alter table public.work_entries add column if not exists shoot_type text;
alter table public.work_entries add column if not exists location text;
alter table public.work_entries add column if not exists participants text;
alter table public.work_entries add column if not exists deliverables text;
update public.work_entries set activity_type = case when activity_type is not null then activity_type when category in ('Series','Other collection','General content','Other') then 'Content Posting' else coalesce(category, 'Content Posting') end;

create table if not exists public.catalog_collections (
  id bigint generated by default as identity primary key,
  name text not null,
  status text not null default 'Upcoming' check (status in ('Upcoming','In Production','Ready to Launch','Published','Archived')),
  source text not null default 'manual' check (source in ('manual','website')),
  source_key text unique,
  website_url text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.catalog_products (
  id bigint generated by default as identity primary key,
  name text not null,
  collection_id bigint references public.catalog_collections(id) on delete set null,
  source text not null default 'manual' check (source in ('manual','website')),
  source_key text unique,
  product_url text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.catalog_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  items_count integer not null default 0,
  status text not null default 'running',
  details text
);

create index if not exists work_entries_user_date_idx on public.work_entries(user_id, work_date desc);
create index if not exists catalog_products_collection_idx on public.catalog_products(collection_id);
create index if not exists catalog_collections_status_idx on public.catalog_collections(status);

alter table public.work_entries enable row level security;
alter table public.catalog_collections enable row level security;
alter table public.catalog_products enable row level security;
alter table public.catalog_sync_runs enable row level security;

-- Replace starter policies safely, so rerunning this script does not fail.
drop policy if exists "Users can read their own entries" on public.work_entries;
drop policy if exists "Users can insert their own entries" on public.work_entries;
drop policy if exists "Users can update their own entries" on public.work_entries;
drop policy if exists "Users can delete their own entries" on public.work_entries;
create policy "Users can read their own entries" on public.work_entries for select to authenticated using (auth.uid() = user_id);
create policy "Users can insert their own entries" on public.work_entries for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can update their own entries" on public.work_entries for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete their own entries" on public.work_entries for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Authenticated users can read catalog collections" on public.catalog_collections;
drop policy if exists "Authenticated users can create catalog collections" on public.catalog_collections;
drop policy if exists "Authenticated users can update catalog collections" on public.catalog_collections;
drop policy if exists "Authenticated users can delete catalog collections" on public.catalog_collections;
create policy "Authenticated users can read catalog collections" on public.catalog_collections for select to authenticated using (true);
create policy "Authenticated users can create catalog collections" on public.catalog_collections for insert to authenticated with check (created_by = auth.uid() and source = 'manual');
create policy "Authenticated users can update catalog collections" on public.catalog_collections for update to authenticated using (source = 'manual') with check (source = 'manual');
create policy "Authenticated users can delete catalog collections" on public.catalog_collections for delete to authenticated using (source = 'manual');

drop policy if exists "Authenticated users can read catalog products" on public.catalog_products;
drop policy if exists "Authenticated users can create catalog products" on public.catalog_products;
drop policy if exists "Authenticated users can update catalog products" on public.catalog_products;
drop policy if exists "Authenticated users can delete catalog products" on public.catalog_products;
create policy "Authenticated users can read catalog products" on public.catalog_products for select to authenticated using (true);
create policy "Authenticated users can create catalog products" on public.catalog_products for insert to authenticated with check (created_by = auth.uid() and source = 'manual');
create policy "Authenticated users can update catalog products" on public.catalog_products for update to authenticated using (source = 'manual') with check (source = 'manual');
create policy "Authenticated users can delete catalog products" on public.catalog_products for delete to authenticated using (source = 'manual');

drop policy if exists "Authenticated users can read catalog sync runs" on public.catalog_sync_runs;
create policy "Authenticated users can read catalog sync runs" on public.catalog_sync_runs for select to authenticated using (true);

-- Link work entries to catalog records, while retaining text snapshots for historical exports.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'work_entries_collection_id_fkey') then
    alter table public.work_entries add constraint work_entries_collection_id_fkey foreign key (collection_id) references public.catalog_collections(id) on delete set null;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'work_entries_product_id_fkey') then
    alter table public.work_entries add constraint work_entries_product_id_fkey foreign key (product_id) references public.catalog_products(id) on delete set null;
  end if;
end $$;
